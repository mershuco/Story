"""Build explicit, auditable kit-based game estimates; never infer empirical win rates."""
import csv
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'research/2026/champion-combat-ratings.tsv'
champions=json.loads((ROOT/'dist/data/season-2026/champions.json').read_text())
rows=list(csv.DictReader(source.open(),delimiter='\t'))
assert len(rows)==len({r['id'] for r in rows})==len(champions)==173
assert {r['id'] for r in rows}=={c['id'] for c in champions}
fields=['skirmish','teamfight','pick','siege','snowball','utility']
profiles={}
for r in rows:
    p={'curve':[float(n) for n in r['curve5_14_24_34_45'].split(',')],**{k:float(r[k]) for k in fields},'note':r['note']}
    assert len(p['curve'])==5 and p['note']
    assert all(1<=n<=5 for n in p['curve']+list(p[k] for k in fields))
    profiles[r['id']]=p
module="// Generated by scripts/build_champion_combat_profiles.py from reviewed kit estimates.\n"
module+="// Scores are game design estimates, not observed champion win rates or patch tier rankings.\n"
module+="export const COMBAT_PROFILE_VERSION='kit-v1';\nexport const CHAMPION_COMBAT_PROFILES={\n"
module+='\n'.join(' '+json.dumps(k)+':'+json.dumps(v,ensure_ascii=False,separators=(',',':'))+',' for k,v in profiles.items())+'\n};\n'
(ROOT/'dist/champion-combat-profiles.js').write_text(module)
# Every rating is linked to the official spell snapshot available for that champion.
evidence=[]
for c in champions:
    versions=[v for v in c['kits'] if c['available'].get(v)]
    version=sorted(versions,key=lambda v:tuple(map(int,v.split('.'))))[0]
    kit=c['kits'][version]
    assert kit['passive']['description'] and len(kit['spells'])==4
    evidence.append({'id':c['id'],'name':c['name'],'kitVersion':version,'officialSource':f'https://ddragon.leagueoflegends.com/cdn/{version}/data/ko_KR/champion/{c["id"]}.json','abilities':[kit['passive']['name']]+[s['name'] for s in kit['spells']],'classification':'kit_based_game_estimate','confidence':'limited_new_champion' if c['id']=='Locke' else 'qualitative_kit_inference'})
(ROOT/'research/2026/champion-combat-sources.json').write_text(json.dumps({'profileVersion':'kit-v1','reviewedOn':'2026-11-24','anchorsMinutes':[5,14,24,34,45],'ratingScale':[1,5],'method':'Explicit per-champion qualitative kit interpretation. No measured time-specific LCK win-rate calibration. Frozen 2026 source snapshots; patch-specific balance, actual builds, stacks and levels are not fully simulated.','champions':evidence},ensure_ascii=False,indent=2)+'\n')
# A human-readable full analysis is downloadable inside the game.
with (ROOT/'dist/data/champion-combat-analysis.csv').open('w',newline='',encoding='utf-8-sig') as f:
    writer=csv.writer(f,lineterminator="\n")
    writer.writerow(['챔피언ID','챔피언','5분','14분','24분','34분','45분','소규모교전','한타','포착','공성','성장전과민감도','열세시유틸유지','강점과한계','공식스킬출처','평가성격'])
    for c,e in zip(champions,evidence):
        p=profiles[c['id']]
        writer.writerow([c['id'],c['name'],*p['curve'],*[p[k] for k in fields],p['note'],e['officialSource'],'1~5점 게임용 추정; 실전 승률 아님'])
print(f'Built {len(profiles)} explicit champion profiles and official snapshot references.')
