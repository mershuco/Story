"""Normalize VSChamp's public qualitative lane matchups into champion/role IDs."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import re
import unicodedata

ROOT = Path(__file__).resolve().parent.parent
SOURCE = "https://vschamp.lol/champ.json?v=1.2.7"
ROLES = {"탑": "TOP", "미드": "MID", "원딜": "BOT", "바텀": "BOT",
         "서폿": "SUP", "서포터": "SUP", "정글": "JGL"}
BOTTOM = {"BOT", "SUP"}
SECTIONS = {"hard_counters": 2, "general_counters": 1}


def name_key(text):
    return re.sub(r"[^\w]", "", unicodedata.normalize("NFKC", text).casefold())


def marked_as_later(victim, reason):
    # A few entries explicitly say the subject wins lane and has a disadvantage later.
    # Require a named subject and a later-game cue before discarding the matchup.
    name = r"\s*".join(map(re.escape, victim.split()))
    subject_wins = re.search(
        rf"라인전(?:만\s*보면|만큼은|에서는|에선|은)\s*(?:당연히\s+)?{name}(?:이|가)\s+"
        r"[^.?!,]{0,18}?(?:유리|우세|우위)", reason)
    return bool(subject_wins and re.search(r"후반|성장|한타|캐리력|승률|같이 크", reason))


def counter_roles(tags, declared):
    # Some ADC guides label support opponents with the shared bottom lane's ADC tag.
    bottom_roles = declared & BOTTOM
    resolved = set(tags - BOTTOM)
    resolved.update((tags & bottom_roles or bottom_roles or tags & BOTTOM) if tags & BOTTOM else ())
    return resolved


def build(snapshot):
    game = json.loads((ROOT / "dist/data/season-2026/champions.json").read_text())
    ids = {name_key(champion["name"]): champion["id"] for champion in game}
    source_roles, opponent_names = {}, {}
    for champion in snapshot:
        name = champion["champion"]
        champion_id = ids[name_key(name)]
        source_roles[champion_id] = {ROLES[line] for line in champion["lines"]}
        for alias in [name, *champion["aliases"]]:
            if alias:
                opponent_names.setdefault(name_key(alias), champion_id)
        opponent_names[name_key(name)] = champion_id

    entries = {}
    excluded = Counter()
    for champion in snapshot:
        name = champion["champion"]
        victim = ids[name_key(name)]
        for section, strength in SECTIONS.items():
            for rule in champion[section]:
                match = re.fullmatch(r"\s*([^()]+?)\s*(?:\(([^()]*)\))?\s*", rule["name"])
                opponent = opponent_names.get(name_key(match[1])) if match else None
                if not opponent or opponent == victim:
                    excluded["non-champion or self"] += 1
                    continue
                tags = {ROLES[tag.strip()] for tag in (match[2] or "").split(",") if tag.strip() in ROLES}
                if marked_as_later(name, rule["reason"]):
                    excluded["subject favored in lane"] += 1
                    continue
                roles = counter_roles(tags, source_roles[opponent])
                lane_pairs = [(r, r) for r in {"TOP", "MID"} & source_roles[victim] & roles]
                lane_pairs.extend((a, b) for a in source_roles[victim] & BOTTOM for b in roles & BOTTOM)
                if not lane_pairs:
                    excluded["outside a shared lane"] += 1
                for victim_role, opponent_role in lane_pairs:
                    pair = f"{victim_role}:{victim}>{opponent_role}:{opponent}"
                    entries[pair] = max(strength, entries.get(pair, 0))
    return source_roles, entries, excluded


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("snapshot", type=Path, help=f"Saved public JSON from {SOURCE}")
    args = parser.parse_args()
    raw = args.snapshot.read_bytes()
    roles, entries, excluded = build(json.loads(raw))
    output = (ROOT / "dist/vschamp-lane-data.js")
    with output.open("w", encoding="utf-8") as file:
        file.write("// Generated by scripts/build_vschamp_lane_counters.py.\n")
        file.write(f"// Source: {SOURCE}\n")
        file.write(f"// Snapshot SHA-256: {hashlib.sha256(raw).hexdigest()}\n")
        file.write("// Keys: disadvantaged role/champion > counter role/champion. 2 = hard, 1 = general.\n")
        file.write("export const VSCHAMP_LANE_DATA = {\n")
        for key, tier in sorted(entries.items()):
            file.write(f' "{key}": {tier},\n')
        file.write("};\n")
    print(f"{len(roles)} champion pages, {len(entries)} lane entries: {dict(Counter(entries.values()))}")
    print(f"Excluded: {dict(excluded)}")
    print("Lane pairs:", dict(Counter(key.split(":")[0] for key in entries)))


if __name__ == "__main__":
    main()
